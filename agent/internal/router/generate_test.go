func TestGenerateRecognisesItsOwnFileAfterACrashBeforeTheStateUpdate(t *testing.T) {
	w := newWorld(t).build()
	res := w.mustGenerate()
	w.ini.sha = "" // a lost state file
	w.alerts.reset()
	again := w.mustGenerate()
	if again.HandEditedCopy != "" || again.Written || w.ini.IniSHA256() != res.SHA256 {
		t.Fatalf("a file that carries the header and equals the render is ours: %+v", again)
	}

	// The recorded hash is stale, but the file holds exactly what a run would write.
	w.ini.sha = sum("stale")
	again = w.mustGenerate()
	if again.HandEditedCopy != "" || w.ini.IniSHA256() != res.SHA256 {
		t.Fatalf("a stale hash on an up-to-date file is not a hand edit: %+v", again)
	}

	// Only the first (time) line differs: nothing is lost, so nothing is reported.
	lines := strings.SplitN(w.iniText(), "\n", 2)
	w.fs.put(iniPath, []byte("; GENERATED by aiagent 9.9.9 at 2030-01-01T00:00:00Z — DO NOT EDIT\n"+lines[1]), 0o640)
	if again = w.mustGenerate(); again.HandEditedCopy != "" {
		t.Fatalf("a changed timestamp line is not a hand edit: %+v", again)
	}
}

