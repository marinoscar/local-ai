// TestGenerateOnTheRealFilesystem runs once against a temp directory and the real atomic writer,
// with a real mode and no fakes, to prove the fake and the real FS agree.
func TestGenerateOnTheRealFilesystem(t *testing.T) {
	root := t.TempDir()
	paths := DefaultPaths(root)
	content := root + "/srv/localai"
	m := aiN3Models()
	real := config.OSFS{}
	for _, mod := range m {
		for _, f := range mod.Files {
			p := modelDir(content, mod.ID) + "/" + f.Name
			if err := os.MkdirAll(modelDir(content, mod.ID), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(p, []byte("gguf"), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		manifestOnDisk(t, content, mod)
	}
	if err := os.MkdirAll(root+"/etc/localai", 0o755); err != nil {
		t.Fatal(err)
	}
	g, err := NewGenerator(GeneratorOptions{
		Paths: paths, FS: real, IniState: &memIni{}, Version: "0.1.0",
		LocalAI:  &Identity{UID: os.Getuid(), GID: os.Getgid()}, // t.TempDir is private to the test user
		INIOwner: Ownership{UID: -1, GID: -1}, DropInOwner: Ownership{UID: -1, GID: -1},
	})
	if err != nil {
		t.Fatal(err)
	}
	in := Inputs{
		NodeID: "ai-n3", Catalog: &catalog.Catalog{Version: "2026.11.02-1", Models: m}, Profile: aiN3Profile(),
		Roots: Roots{Internal: content}, Fit: NewEnv(snapAiN3(), "cuda", routerBlock(1, 512), 0),
		Llama: config.LlamaBlock{ExtraEnv: map[string]string{"GGML_X": "1"}},
	}
	res, err := g.Generate(context.Background(), in)
	if err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(paths.INI)
	if err != nil || info.Mode().Perm() != 0o640 {
		t.Fatalf("models.ini: %v %v", info, err)
	}
	di, err := os.Stat(paths.DropIn)
	if err != nil || di.Mode().Perm() != 0o644 {
		t.Fatalf("drop-in: %v %v", di, err)
	}
	b, _ := os.ReadFile(paths.INI)
	if !strings.Contains(string(b), "model = "+content+"/models/qwen3.5-9b-q4km/Qwen3.5-9B-Q4_K_M.gguf") || res.SHA256 != SHA256Hex(b) {
		t.Fatalf("file:\n%s\nresult %+v", b, res)
	}
	entries, _ := os.ReadDir(root + "/etc/localai")
	for _, e := range entries {
		if strings.Contains(e.Name(), ".tmp-") {
			t.Fatalf("temp file left behind: %s", e.Name())
		}
	}
}
