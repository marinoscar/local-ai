		w.build()
		w.mustGenerate()
		got, _ := w.fs.get(dropInPath)
		if strings.Contains(string(got), vk) || !strings.Contains(string(got), "GGML_OK=yes") {
			t.Fatalf("drop-in:\n%s", got)
		}
		if !w.alerts.has("raise", CodePresetEnvConflict, vk) {
			t.Fatalf("LAI-LLM-015 not raised: %+v", w.alerts.events)
		}
		// Fixing the catalog clears it.
		w.models[1].Llama.Env = map[string]string{vk: "1"}
		w.alerts.reset()
		w.mustGenerate()
		if !w.alerts.has("clear", CodePresetEnvConflict, vk) {
			t.Fatal("LAI-LLM-015 not cleared")
		}
