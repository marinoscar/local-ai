// TestGenerateDeterministicAcrossOrders: shuffling the catalog, the drives, the alias lists and
// repeating the run never changes a byte (seeded property test).
func TestGenerateDeterministicAcrossOrders(t *testing.T) {
	ref := ""
	for seed := int64(0); seed < 25; seed++ {
		rng := rand.New(rand.NewSource(seed))
		w := aiN1World(t)
		w.llama.LegacyAliases = map[string][]string{
			"qwen3-coder-next-q4km": {"qwen3-coder-next", "coder-legacy"},
			"large-vlm-q4km":        {"vlm-legacy"},
		}
		rng.Shuffle(len(w.models), func(a, b int) { w.models[a], w.models[b] = w.models[b], w.models[a] })
		for i := range w.models {
			f := w.models[i].Files
			rng.Shuffle(len(f), func(a, b int) { f[a], f[b] = f[b], f[a] })
		}
		for _, m := range w.models {
			installModel(w.fs, "/media/ark-"+string(rune('a'+rng.Intn(3))), m)
		}
		drives := []string{"/media/ark-a", "/media/ark-b", "/media/ark-c"}
		rng.Shuffle(len(drives), func(a, b int) { drives[a], drives[b] = drives[b], drives[a] })
		w.roots = Roots{Internal: rootInternal, Drives: drives}
		w.build().mustGenerate()
		got := string(StripHeaderLine([]byte(w.iniText())))
		if ref == "" {
			ref = got
		}
		if got != ref {
			t.Fatalf("seed %d: output depends on input order:\n%s\n---\n%s", seed, got, ref)
		}
	}
}

