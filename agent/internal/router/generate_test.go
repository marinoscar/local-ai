// TestApplyResyncAfterAnAgentRestart: a new Generator (the agent restarted) finds the file
// unchanged, but the router lists other presets than the file has (the reload that should have
// followed the last write never happened).
func TestApplyResyncAfterAnAgentRestart(t *testing.T) {
	rw := withRouter(t)
	rw.r.set(st("qwen3.5-9b-q4km", StatusLoaded), ModelStatus{ID: "stray-cache-model", Status: StatusUnloaded, Source: SourceCache})
	rw.reset()
	rw.build()                                    // a fresh Generator over the same disk and state
	rw.r.set(st("qwen3.5-9b-q4km", StatusLoaded)) // the router has only one of the two sections
	res := rw.mustGenerate()
	if res.Written || !res.Reloaded || res.Reload.Reason != ReasonResync {
		t.Fatalf("result: %+v", res)
	}
	equalStrings(t, res.Reload.Kept, []string{"qwen3.5-9b-q4km"})
	// Once synced it is quiet.
	rw.reset()
	rw.r.set(st("qwen3.5-9b-q4km", StatusLoaded))
	if res := rw.mustGenerate(); res.Reloaded {
		t.Fatalf("a synced generator must not resync: %+v", res)
	}
	// And a router that lists the same presets is not reloaded at the first run either (cache
	// models are not ours).
	rw.build()
	rw.reset()
	rw.r.set(st("qwen3.5-9b-q4km", StatusLoaded), st("small-vlm-q4km", StatusUnloaded), ModelStatus{ID: "stray", Source: SourceCache, Status: StatusUnloaded})
	if res := rw.mustGenerate(); res.Reloaded {
		t.Fatalf("matching presets: %+v", res)
	}
}

