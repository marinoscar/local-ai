func TestGenerateHandEditedFileIsSavedAside(t *testing.T) {
	w := newWorld(t).build()
	w.mustGenerate()
	good := w.iniText()
	w.fs.put(iniPath, []byte(good+"\n[evil]\nmodel = /etc/passwd\n"), 0o640)
	w.alerts.reset()

	res := w.mustGenerate()
	if !res.Written || w.iniText() != good {
		t.Fatalf("the edited file was not regenerated: written=%v", res.Written)
	}
	saved := iniPath + ".hand-edited-20261102T150405Z"
	if res.HandEditedCopy != saved {
		t.Fatalf("copy at %q, want %q", res.HandEditedCopy, saved)
	}
	if b, ok := w.fs.get(saved); !ok || !strings.Contains(string(b), "[evil]") {
		t.Fatal("the saved copy does not hold the edit")
	}
	if !w.alerts.has("raise", CodePresetHandEdited, "") {
		t.Fatalf("LAI-LLM-006 not raised: %+v", w.alerts.events)
	}
	found := false
	for _, f := range res.Findings {
		found = found || f.Code == CodePresetHandEdited
	}
	if !found {
		t.Fatal("the finding is not in the result")
	}

	// The next run is clean and does not raise it again.
	w.alerts.reset()
	if res := w.mustGenerate(); res.HandEditedCopy != "" || w.alerts.has("raise", CodePresetHandEdited, "*") {
		t.Fatal("a regenerated file was reported as edited again")
	}
}

