package router

import (
	"bytes"
	"fmt"
	"regexp"
	"sort"
	"strings"
	"unicode"

	"github.com/marinoscar/local-ai/agent/internal/catalog"
)

// DropInHeader is the first line of the environment drop-in (llama-router.md section 3.3).
const DropInHeader = "# GENERATED by aiagent — do not edit. Spec: docs/specs/llama-router.md §3.3\n"

// maxNodeEnvValueChars is the limit of a node.yaml llama.extra_env value (agent.md section 3.4).
const maxNodeEnvValueChars = 256

var (
	// catalogEnvKeyRe is a valid environment variable name (what catalog lint accepts).
	catalogEnvKeyRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	// nodeEnvKeyRe is the key rule of node.yaml llama.extra_env (agent.md section 3.4).
	nodeEnvKeyRe = regexp.MustCompile(`^(GGML|LLAMA|CUDA)_[A-Z0-9_]+$`)
)

// Env sources, for EnvReject.Source.
const (
	EnvSourceCatalog = "catalog"
	EnvSourceNode    = "node.yaml"
)

// EnvConflict is a variable that two models set to different values while node.yaml does not set
// it: it is left out of the drop-in (LAI-LLM-015).
type EnvConflict struct {
	Key string
	// Models are the model ids that set the key, sorted; Values are their values, in the same order.
	Models []string
	Values []string
}

// EnvReject is a variable the merge refused (a name the router owns or that is not a valid name,
// a value that is not one line). The value is never recorded.
type EnvReject struct {
	Key    string
	Source string
	Model  string
	Reason string
}

// EnvMerge is the result of MergeEnv.
type EnvMerge struct {
	// Env is the merged environment of the drop-in.
	Env       map[string]string
	Conflicts []EnvConflict
	Rejected  []EnvReject
}

// MergeEnv is llama-router.md section 4.2 step 6: the union of llama.env over the models in the
// file, plus node.yaml llama.extra_env, and the node's value wins. Two models that set the same
// variable to different values, with no node value, drop the variable and report a conflict. A
// model that is not in models contributes nothing. The router's own LLAMA_ARG_* variables are
// refused from both sources (the router sets them, and an inherited one would override its
// arguments).
func MergeEnv(models []*catalog.Model, nodeEnv map[string]string) EnvMerge {
	out := EnvMerge{Env: map[string]string{}}
	node := map[string]string{}
	for _, k := range sortedKeys(nodeEnv) {
		v := nodeEnv[k]
		switch {
		case strings.HasPrefix(k, "LLAMA_ARG_"):
			out.Rejected = append(out.Rejected, EnvReject{Key: k, Source: EnvSourceNode, Reason: "LLAMA_ARG_* variables are set by the router"})
		case !nodeEnvKeyRe.MatchString(k):
			out.Rejected = append(out.Rejected, EnvReject{Key: clip(k, 40), Source: EnvSourceNode, Reason: "the name must start with GGML_, LLAMA_ or CUDA_"})
		case len([]rune(v)) > maxNodeEnvValueChars || strings.IndexFunc(v, func(r rune) bool { return !unicode.IsPrint(r) }) >= 0:
			out.Rejected = append(out.Rejected, EnvReject{Key: k, Source: EnvSourceNode, Reason: "the value must be printable and at most 256 characters"})
		default:
			node[k] = v
		}
	}

	type setting struct{ model, value string }
	byKey := map[string][]setting{}
	var ordered []*catalog.Model
	for _, m := range models {
		if m != nil && m.Llama != nil {
			ordered = append(ordered, m)
		}
	}
	sort.Slice(ordered, func(a, b int) bool { return ordered[a].ID < ordered[b].ID })
	for _, m := range ordered {
		for _, k := range sortedKeys(m.Llama.Env) {
			v := m.Llama.Env[k]
			switch {
			case strings.HasPrefix(k, "LLAMA_ARG_"):
				out.Rejected = append(out.Rejected, EnvReject{Key: k, Source: EnvSourceCatalog, Model: m.ID, Reason: "LLAMA_ARG_* variables are set by the router"})
			case !catalogEnvKeyRe.MatchString(k):
				out.Rejected = append(out.Rejected, EnvReject{Key: clip(k, 40), Source: EnvSourceCatalog, Model: m.ID, Reason: "not a valid variable name"})
			case strings.ContainsAny(v, "\n\r\x00"):
				out.Rejected = append(out.Rejected, EnvReject{Key: k, Source: EnvSourceCatalog, Model: m.ID, Reason: "the value must be one line"})
			default:
				byKey[k] = append(byKey[k], setting{m.ID, v})
			}
		}
	}

	for _, k := range sortedKeys(byKey) {
		if v, ok := node[k]; ok {
			out.Env[k] = v // the node wins, conflict or not
			continue
		}
		set := byKey[k]
		same := true
		for _, s := range set[1:] {
			if s.value != set[0].value {
				same = false
				break
			}
		}
		if same {
			out.Env[k] = set[0].value
			continue
		}
		c := EnvConflict{Key: k}
		for _, s := range set {
			c.Models = append(c.Models, s.model)
			c.Values = append(c.Values, s.value)
		}
		out.Conflicts = append(out.Conflicts, c)
	}
	for k, v := range node {
		out.Env[k] = v
	}
	return out
}

// RenderDropIn renders /etc/systemd/system/localai-llama.service.d/50-env.conf (llama-router.md
// section 3.3): the header, [Service] and one Environment= line per variable, sorted by name. An
// empty environment returns nil: the file is then absent, not empty. A value with white space,
// quotes or a backslash is written as "NAME=value" in double quotes with those escaped; '%' is
// doubled, because systemd expands specifiers in unit files.
func RenderDropIn(env map[string]string) []byte {
	if len(env) == 0 {
		return nil
	}
	var b bytes.Buffer
	b.WriteString(DropInHeader)
	b.WriteString("[Service]\n")
	for _, k := range sortedKeys(env) {
		v := strings.ReplaceAll(env[k], "%", "%%")
		if strings.ContainsAny(v, " \t\"'\\") {
			v = strings.ReplaceAll(strings.ReplaceAll(v, `\`, `\\`), `"`, `\"`)
			fmt.Fprintf(&b, "Environment=\"%s=%s\"\n", k, v)
			continue
		}
		fmt.Fprintf(&b, "Environment=%s=%s\n", k, v)
	}
	return b.Bytes()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
