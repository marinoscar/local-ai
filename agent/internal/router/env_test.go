func withEnv(id string, env map[string]string) *catalog.Model {
	m := llamaModel(id, []string{"chat"}, 1, 1, nil, &catalog.Llama{Ctx: 1, Env: env})
	return &m
}

func TestMergeEnv(t *testing.T) {
	const vk = "GGML_VK_SUBALLOCATION_BLOCK_SIZE"
	cases := []struct {
		name      string
		models    []*catalog.Model
		node      map[string]string
		want      map[string]string
		conflicts []string // keys
	}{
		{"no models, no node env", nil, nil, map[string]string{}, nil},
		{"models without env", []*catalog.Model{withEnv("a-model", nil), withEnv("b-model", nil)}, nil, map[string]string{}, nil},
		{"one model", []*catalog.Model{withEnv("a-model", map[string]string{vk: "4294967296"})}, nil,
			map[string]string{vk: "4294967296"}, nil},
		{"two models, equal values", []*catalog.Model{
			withEnv("a-model", map[string]string{vk: "1"}), withEnv("b-model", map[string]string{vk: "1"})}, nil,
			map[string]string{vk: "1"}, nil},
		{"two models, different keys are a union", []*catalog.Model{
			withEnv("a-model", map[string]string{"GGML_A": "1"}), withEnv("b-model", map[string]string{"GGML_B": "2"})}, nil,
			map[string]string{"GGML_A": "1", "GGML_B": "2"}, nil},
		{"two models, conflicting values: the key is dropped", []*catalog.Model{
			withEnv("a-model", map[string]string{vk: "1", "GGML_OK": "x"}), withEnv("b-model", map[string]string{vk: "2"})}, nil,
			map[string]string{"GGML_OK": "x"}, []string{vk}},
		{"three models, one differs", []*catalog.Model{
			withEnv("a-model", map[string]string{vk: "1"}), withEnv("b-model", map[string]string{vk: "1"}),
			withEnv("c-model", map[string]string{vk: "9"})}, nil,
			map[string]string{}, []string{vk}},
		{"node value only", nil, map[string]string{vk: "7"}, map[string]string{vk: "7"}, nil},
		{"node overrides a model", []*catalog.Model{withEnv("a-model", map[string]string{vk: "1"})},
			map[string]string{vk: "7"}, map[string]string{vk: "7"}, nil},
		{"node resolves a conflict, so no conflict is reported", []*catalog.Model{
			withEnv("a-model", map[string]string{vk: "1"}), withEnv("b-model", map[string]string{vk: "2"})},
			map[string]string{vk: "7"}, map[string]string{vk: "7"}, nil},
		{"node adds a key the models lack", []*catalog.Model{withEnv("a-model", map[string]string{"GGML_A": "1"})},
			map[string]string{"CUDA_X": "2"}, map[string]string{"GGML_A": "1", "CUDA_X": "2"}, nil},
		{"nil entries are skipped", []*catalog.Model{nil, withEnv("a-model", map[string]string{"GGML_A": "1"})}, nil,
			map[string]string{"GGML_A": "1"}, nil},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := MergeEnv(tc.models, tc.node)
			if !reflect.DeepEqual(got.Env, tc.want) {
				t.Fatalf("Env = %v, want %v", got.Env, tc.want)
			}
			var keys []string
			for _, c := range got.Conflicts {
				keys = append(keys, c.Key)
			}
			equalStrings(t, keys, tc.conflicts)
			if len(got.Rejected) != 0 {
				t.Fatalf("rejected: %+v", got.Rejected)
			}
		})
	}
}

func TestMergeEnvConflictNamesTheModels(t *testing.T) {
	got := MergeEnv([]*catalog.Model{
		withEnv("b-model", map[string]string{"GGML_K": "2"}),
		withEnv("a-model", map[string]string{"GGML_K": "1"}),
	}, nil)
	if len(got.Conflicts) != 1 {
		t.Fatalf("conflicts: %+v", got.Conflicts)
	}
	c := got.Conflicts[0]
	equalStrings(t, c.Models, []string{"a-model", "b-model"})
	equalStrings(t, c.Values, []string{"1", "2"})
}

func TestMergeEnvRefusals(t *testing.T) {
	got := MergeEnv([]*catalog.Model{withEnv("a-model", map[string]string{
		"LLAMA_ARG_PORT": "1", "bad key": "x", "GGML_MULTI": "a\nb", "GGML_OK": "1", "lower": "fine",
	})}, map[string]string{
		"LLAMA_ARG_HOST": "x", "PATH": "/bin", "GGML_LONG": strings.Repeat("x", 257), "GGML_CTRL": "a\x01b", "CUDA_OK": "1",
	})
	want := map[string]string{"GGML_OK": "1", "lower": "fine", "CUDA_OK": "1"}
	if !reflect.DeepEqual(got.Env, want) {
		t.Fatalf("Env = %v, want %v", got.Env, want)
	}
	var rejected []string
	for _, r := range got.Rejected {
		rejected = append(rejected, r.Source+":"+r.Key)
	}
	sortStrings(rejected)
	equalStrings(t, rejected, []string{
		"catalog:GGML_MULTI", "catalog:LLAMA_ARG_PORT", "catalog:bad key",
		"node.yaml:GGML_CTRL", "node.yaml:GGML_LONG", "node.yaml:LLAMA_ARG_HOST", "node.yaml:PATH",
	})
	for _, r := range got.Rejected {
		if r.Reason == "" {
			t.Errorf("%+v has no reason", r)
		}
	}
}

func TestRenderDropIn(t *testing.T) {
	if RenderDropIn(nil) != nil || RenderDropIn(map[string]string{}) != nil {
		t.Fatal("an empty environment has no drop-in")
	}
	got := string(RenderDropIn(map[string]string{"GGML_VK_SUBALLOCATION_BLOCK_SIZE": "4294967296"}))
	want := "# GENERATED by aiagent — do not edit. Spec: docs/specs/llama-router.md §3.3\n" +
		"[Service]\nEnvironment=GGML_VK_SUBALLOCATION_BLOCK_SIZE=4294967296\n"
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}

	// Sorted by name, and quoting only where systemd needs it.
	got = string(RenderDropIn(map[string]string{
		"GGML_Z": "1", "GGML_A": "has space", "GGML_Q": `say "hi"`, "GGML_B": `back\slash`, "GGML_P": "50%", "GGML_E": "",
	}))
	want = "# GENERATED by aiagent — do not edit. Spec: docs/specs/llama-router.md §3.3\n[Service]\n" +
		"Environment=\"GGML_A=has space\"\n" +
		"Environment=\"GGML_B=back\\\\slash\"\n" +
		"Environment=GGML_E=\n" +
		"Environment=GGML_P=50%%\n" +
		"Environment=\"GGML_Q=say \\\"hi\\\"\"\n" +
		"Environment=GGML_Z=1\n"
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
}

func TestDropInIsDeterministic(t *testing.T) {
	env := map[string]string{}
	for _, k := range []string{"GGML_A", "GGML_B", "CUDA_C", "LLAMA_D", "GGML_E"} {
		env[k] = k
	}
	first := string(RenderDropIn(env))
	for i := 0; i < 20; i++ {
		if string(RenderDropIn(env)) != first {
			t.Fatal("the drop-in depends on map order")
		}
	}
}
