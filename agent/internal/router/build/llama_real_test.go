// TestLlamaRealBuild builds llama.cpp for real (the CPU backend), the way `aictl rebuild-llama --from-kit`
// does, from a kit-style source tarball: the CI job `llama-build` (.github/workflows/llama-build.yml)
// runs it inside a network namespace (`unshare -n`) at a pinned release tag, and an operator can run it
// by hand. It is skipped unless LOCALAI_LLAMA_KIT_TARBALL names a file called llama.cpp-<40 hex>.tar.gz
// (the layout of kit/src/, one top-level directory):
//
//	LOCALAI_LLAMA_KIT_TARBALL    the source tarball (required)
//	LOCALAI_LLAMA_MODEL          a GGUF model for the completion of the smoke test and of the post-switch
//	                             check; without it a tiny llama model is generated by this test
//	                             (llama_gguf_test.go), so the completion step always runs
//	LOCALAI_LLAMA_JOBS           the -j of the compile (default: the engine's own computation)
//	LOCALAI_EXPECT_NO_NETWORK=1  fail unless the network really is unreachable
//
// It proves four things on the real programs (KIT-04 and KIT-05, rebuild-kit.md sections 4.2 and 4.3):
//
//  1. The build from the kit tarball passes the preflight, the compile, the smoke test (--version,
//     --list-devices and a completion with the tiny model) and is activated: `current` points at it,
//     the "service" restarted on it and the post-switch check (health, default model, a 16 token
//     completion with the real llama-cli) passed.
//  2. The activated build was exported (Options.Exporter, kit.PrebuiltExporter) and the export restores
//     into a second root as `--prebuilt` does (Request.Prebuilt): the programs and BUILD.json are the
//     exported bytes, nothing is compiled, and the restored build passes the same smoke test and is
//     activated.
//  3. A build whose llama-server is a wrapper that passes the smoke test but fails as a service is
//     rolled back: LAI-LLM-019, current points at the previous build again and the service was
//     restarted on it.
//  4. Nothing in the build, the restore, the rollback or their logs says LAI-KIT-022 (retired).
//
// The service is a stand-in (no systemd and no router in CI): restarting it runs
// `current/bin/llama-server --version` with LOCALAI_SERVICE=1 in the environment, and the post-switch
// check asks the new llama-cli for a real completion. The build runs as the caller (a CI runner has no
// localai user).
func TestLlamaRealBuild(t *testing.T) {
	tarball := os.Getenv("LOCALAI_LLAMA_KIT_TARBALL")
	if tarball == "" {
		t.Skip("set LOCALAI_LLAMA_KIT_TARBALL to build llama.cpp for real (see the comment of this test)")
	}
	m := regexp.MustCompile(`^llama\.cpp-([0-9a-f]{40})\.tar\.gz$`).FindStringSubmatch(filepath.Base(tarball))
	if m == nil {
		t.Fatalf("the tarball %q is not named llama.cpp-<40 hex>.tar.gz", tarball)
	}
	commit := m[1]
	// A fresh network namespace has loopback down, and llama-cli talks to the server it starts itself
	// over 127.0.0.1: bring lo up (it is no network; the checks below still prove there is none).
	if err := bringUpLoopback(); err != nil {
		t.Logf("loopback could not be brought up: %v", err)
	}
	if os.Getenv("LOCALAI_EXPECT_NO_NETWORK") == "1" {
		ifaces, err := net.Interfaces()
		if err != nil {
			t.Fatal(err)
		}
		for _, i := range ifaces {
			if i.Flags&net.FlagLoopback == 0 {
				t.Fatalf("the interface %s exists: this build must run in a network namespace with loopback only", i.Name)
			}
		}
		if c, err := net.DialTimeout("tcp", "1.1.1.1:443", 2*time.Second); err == nil {
			_ = c.Close()
			t.Fatal("the network is reachable: this build must run with it disabled")
		}
		if c, err := net.DialTimeout("tcp", "github.com:443", 2*time.Second); err == nil {
			_ = c.Close()
			t.Fatal("the network is reachable (github.com answers): this build must run with it disabled")
		}
	}
	jobs := 0
	if s := os.Getenv("LOCALAI_LLAMA_JOBS"); s != "" {
		if _, err := fmt.Sscan(s, &jobs); err != nil {
			t.Fatalf("LOCALAI_LLAMA_JOBS=%q: %v", s, err)
		}
	}

	// A kit: the tarball and the digest the kit records for it.
	data, err := os.ReadFile(tarball)
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(data)
	kitRoot := t.TempDir()
	kitSrc := filepath.Join(kitRoot, "kit", "src")
	if err := os.MkdirAll(kitSrc, 0o755); err != nil {
		t.Fatal(err)
	}
	name := filepath.Base(tarball)
	if err := os.WriteFile(filepath.Join(kitSrc, name), data, 0o644); err != nil {
		t.Fatal(err)
	}
	manifest := fmt.Sprintf(`{"schema_version":1,"files":[{"kind":"source_tarball","path":%q,"sha256":%q}]}`, name, hex.EncodeToString(sum[:]))
	if err := os.WriteFile(filepath.Join(kitSrc, "MANIFEST.json"), []byte(manifest), 0o644); err != nil {
		t.Fatal(err)
	}

	model := os.Getenv("LOCALAI_LLAMA_MODEL")
	if model == "" {
		model = filepath.Join(t.TempDir(), "tiny.gguf")
		writeTinyGGUF(t, model)
	}

	root1, scratch1 := filepath.Join(t.TempDir(), "llama.cpp"), t.TempDir()
	exportRoot := t.TempDir()
	ex := &kit.PrebuiltExporter{
		FS: kit.OSFS{}, Roots: func() []string { return []string{exportRoot} }, Program: kit.ProgramLlama,
		Codename: "testrelease", Arch: kitArch(runtime.GOARCH),
		NodeID: func() string { return "node-ci" }, Kernel: func() string { return "ci" },
	}
	svc1 := &realService{root: root1, model: model}
	mgr := New(Options{
		Root: root1, ScratchDir: scratch1, KitRoots: func() []string { return []string{kitRoot} }, CompileUser: CompileAsCaller,
		Defaults: func() Defaults { return Defaults{Commit: commit, Backend: BackendCPU, LlamaBackend: BackendCPU} },
		BuiltBy:  "aiagent test", Exec: execx.Exec{},
		SmokeModel: func() (string, bool) { return model, true },
		Agent:      svc1, Probe: svc1, Exporter: ex,
	})

	ctx, cancel := context.WithTimeout(context.Background(), 100*time.Minute)
	defer cancel()
	var seen []string // every message the engine produced, for the LAI-KIT-022 scan
	note := func(s ...string) { seen = append(seen, s...) }

	// 1. The offline preflight, the build, the smoke test and the activation.
	rep := mgr.PreflightReport(ctx, Request{FromKit: true, Offline: true})
	for _, c := range rep.Checks {
		t.Logf("preflight %-8s ok=%v %s", c.ID, c.OK, c.Detail)
		note(c.Code, c.Detail)
	}
	if !rep.OK() {
		t.Fatalf("the preflight failed: %v", failedIDs(rep))
	}
	res, err := mgr.Build(ctx, Request{FromKit: true, Offline: true, Jobs: jobs, Progress: func(p Progress) { t.Logf("[%s] %s", p.Stage, p.Message) }})
	if err != nil {
		failReal(t, "build", err)
	}
	note(res.Warnings...)
	t.Logf("build %s, switched %v, default model %q, warnings %v", res.BuildID, res.Switched, res.DefaultModel, res.Warnings)
	if res.BuildID != commit[:9]+"-"+BackendCPU || !res.Switched || res.Restored {
		t.Errorf("result = %+v", res)
	}
	for _, w := range res.Warnings {
		if strings.Contains(w, "not asked to write") || strings.Contains(w, "could not be exported") || strings.Contains(w, "could not be updated") {
			t.Errorf("warning: %s", w)
		}
	}
	for _, n := range binaries {
		p := filepath.Join(res.Path, "bin", n)
		if fi, err := os.Stat(p); err != nil || fi.Mode().Perm()&0o111 == 0 || fi.Size() == 0 {
			t.Fatalf("%s: %v %v", p, fi, err)
		}
	}
	info := readBuildInfo(t, filepath.Join(res.Path, "BUILD.json"))
	t.Logf("BUILD.json: %+v", info)
	if info.Backend != BackendCPU || info.Commit != commit || !strings.Contains(info.Smoke.Version, commit[:7]) {
		t.Errorf("BUILD.json = %+v", info)
	}
	if cur := resolveLink(t, root1); cur != res.Path {
		t.Errorf("current points at %s, want %s", cur, res.Path)
	}
	if got := svc1.events(); len(got) != 1 || got[0] != res.BuildID+":started" {
		t.Errorf("the service was restarted as %v", got)
	}
	if svc1.completions != 1 {
		t.Errorf("the post-switch check asked for %d completions, want 1", svc1.completions)
	}
	if _, err := os.Stat(filepath.Join(root1, "src", commit)); err != nil {
		t.Errorf("the kit source was not extracted into src/<commit>: %v", err)
	}
	if left, _ := filepath.Glob(filepath.Join(scratch1, "llama.cpp-*")); len(left) != 0 {
		t.Errorf("a source tree was built from the scratch directory: %v", left)
	}

	// 2. The export and the restore into a second root, with --prebuilt semantics.
	exported := filepath.Join(kit.PrebuiltDir(exportRoot), kit.PrebuiltName(kit.ProgramLlama, commit, BackendCPU, "testrelease", kitArch(runtime.GOARCH), ""))
	exportedSum := fileSHA(t, exported)
	t.Logf("exported %s", exported)
	root2 := filepath.Join(t.TempDir(), "llama.cpp")
	svc2 := &realService{root: root2, model: model}
	opt2 := mgr.opt
	opt2.Root, opt2.ScratchDir, opt2.Agent, opt2.Probe, opt2.Exporter = root2, t.TempDir(), svc2, svc2, nil
	restored, err := New(opt2).Build(ctx, Request{Prebuilt: exported, PrebuiltSHA256: exportedSum})
	if err != nil {
		failReal(t, "restore", err)
	}
	note(restored.Warnings...)
	if !restored.Restored || !restored.Switched || restored.BuildID != res.BuildID {
		t.Errorf("restore = %+v", restored)
	}
	if cur := resolveLink(t, root2); cur != restored.Path {
		t.Errorf("after the restore current points at %s, want %s", cur, restored.Path)
	}
	if got := svc2.events(); len(got) != 1 || got[0] != res.BuildID+":started" || svc2.completions != 1 {
		t.Errorf("restored service events %v, completions %d", got, svc2.completions)
	}
	for _, n := range binaries {
		if !bytes.Equal(readBytes(t, filepath.Join(res.Path, "bin", n)), readBytes(t, filepath.Join(restored.Path, "bin", n))) {
			t.Errorf("%s differs after the restore", n)
		}
	}
	if !bytes.Equal(readBytes(t, filepath.Join(res.Path, "BUILD.json")), readBytes(t, filepath.Join(restored.Path, "BUILD.json"))) {
		t.Error("BUILD.json was changed by the restore")
	}
	if left, _ := filepath.Glob(filepath.Join(root2, "builds", "*.tmp*")); len(left) != 0 {
		t.Errorf("the restore left scratch folders: %v", left)
	}

	// 3. A llama-server that passes the smoke test and fails as a service: restored over the active
	// build of the first root, it must be rolled back.
	wrapper := compileFailingServer(t)
	injected := filepath.Join(t.TempDir(), "injected.tar.gz")
	injectedSum := injectFailingServer(t, exported, injected, wrapper)
	before := fileSHA(t, filepath.Join(res.Path, "bin", "llama-server"))
	_, err = mgr.Build(ctx, Request{Prebuilt: injected, PrebuiltSHA256: injectedSum})
	var be *Error
	if !errors.As(err, &be) {
		t.Fatalf("the injected build was not refused: %v", err)
	}
	note(be.Code, be.Message, fmt.Sprint(be.Details))
	t.Logf("injected build refused: %s: %s (%v)", be.Code, be.Message, be.Details["cause"])
	if be.Code != doctor.LLM019 || be.Details["rolled_back"] != true || be.Details["cause"] != "restart_failed" {
		t.Errorf("error = %s %v", be.Code, be.Details)
	}
	events := svc1.events()
	if len(events) != 3 || events[1] != res.BuildID+":failed" || !strings.HasSuffix(events[2], ":started") || events[2] == res.BuildID+":started" {
		// events[2] is the restart on the previous build, which was moved aside to <id>.old-<ts>.
		t.Errorf("service events after the injected build: %v", events)
	}
	prev := resolveLink(t, root1)
	if !strings.HasPrefix(filepath.Base(prev), res.BuildID+infixOld) {
		t.Errorf("current points at %s, want the previous build %s%s<ts>", prev, res.BuildID, infixOld)
	}
	if after := fileSHA(t, filepath.Join(prev, "bin", "llama-server")); after != before {
		t.Errorf("current serves llama-server %s, want the previous build's %s", after, before)
	}

	// 4. Nothing says LAI-KIT-022 (retired in v0.1, replaced by LAI-LLM-019), in the engine's messages
	// or in any build log.
	logs, _ := filepath.Glob(filepath.Join(root1, "builds", "*", "build.log"))
	logs2, _ := filepath.Glob(filepath.Join(root2, "builds", "*", "build.log"))
	for _, l := range append(logs, logs2...) {
		note(string(readBytes(t, l)))
	}
	for _, s := range seen {
		if strings.Contains(s, doctor.KIT022) {
			t.Errorf("%s was emitted: %s", doctor.KIT022, s)
		}
	}
}

// realService stands in for the agent and the router around the real programs. The agent restarts
// "the service" by running the activated llama-server with LOCALAI_SERVICE=1 (a program that cannot
// start fails the restart), and the router's post-switch check is a real completion with the
// activated llama-cli.
type realService struct {
	root        string
	model       string
	log         []string
	completions int
}

func (s *realService) events() []string { return append([]string(nil), s.log...) }

// Up implements Agent.
func (s *realService) Up(context.Context) bool { return true }

// RestartLlama implements Agent.
func (s *realService) RestartLlama(ctx context.Context) error {
	dir, err := filepath.EvalSymlinks(filepath.Join(s.root, currentLink))
	if err != nil {
		return err
	}
	res, err := execx.Exec{}.Run(ctx, execx.Cmd{
		Path: filepath.Join(dir, "bin", "llama-server"), Args: []string{"--version"}, Timeout: time.Minute, MaxOut: 1 << 20,
		Env: append(toolEnv(), "LOCALAI_SERVICE=1"),
	})
	id := filepath.Base(dir)
	if err != nil || res.ExitCode != 0 {
		s.log = append(s.log, id+":failed")
		return fmt.Errorf("llama-server did not start: %v (exit status %d): %s", err, res.ExitCode, strings.TrimSpace(string(res.Stderr)))
	}
	s.log = append(s.log, id+":started")
	return nil
}

// Health implements Probe.
func (s *realService) Health(context.Context) error { return nil }

// DefaultModel implements Probe.
func (s *realService) DefaultModel(context.Context) (string, error) { return "tiny", nil }

// ModelStatus implements Probe.
func (s *realService) ModelStatus(context.Context, string) (string, error) { return StatusLoaded, nil }

// LoadModel implements Probe.
func (s *realService) LoadModel(context.Context, string) error { return nil }

// Complete implements Probe: the activated llama-cli writes maxTokens tokens with the model.
func (s *realService) Complete(ctx context.Context, _ string, maxTokens int) error {
	dir, err := filepath.EvalSymlinks(filepath.Join(s.root, currentLink))
	if err != nil {
		return err
	}
	res, err := execx.Exec{}.Run(ctx, execx.Cmd{
		Path: filepath.Join(dir, "bin", "llama-cli"), Timeout: GenerateTimeout, MaxOut: 1 << 20, Env: toolEnv(),
		Args: []string{"-m", s.model, "-n", fmt.Sprint(maxTokens), "-p", "Hello", "--no-warmup"},
	})
	if err != nil {
		return err
	}
	if res.ExitCode != 0 {
		return fmt.Errorf("llama-cli exited with status %d", res.ExitCode)
	}
	if strings.TrimSpace(string(res.Stdout)) == "" {
		return errors.New("llama-cli wrote nothing")
	}
	s.completions++
	return nil
}

// wrapperSource is a program that answers like llama-server (it hands every call to llama-server.real
// next to it) except as a service, which is LOCALAI_SERVICE in the environment: then it fails. It is
// an ELF so that it passes the relocatable check of the engine.
const wrapperSource = `#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
int main(int argc, char **argv) {
	char self[4096];
	ssize_t n;
	(void)argc;
	if (getenv("LOCALAI_SERVICE")) {
		fprintf(stderr, "injected failure: the service does not start\n");
		return 1;
	}
	n = readlink("/proc/self/exe", self, sizeof(self) - 16);
	if (n <= 0) return 2;
	self[n] = 0;
	strcat(self, ".real");
	execv(self, argv);
	return 3;
}
`

// compileFailingServer compiles wrapperSource with the C compiler of the build and returns the
// program.
func compileFailingServer(t *testing.T) []byte {
	t.Helper()
	cc, err := execx.Lookup("cc")
	if err != nil {
		t.Fatalf("no C compiler for the injected failure: %v", err)
	}
	dir := t.TempDir()
	src, out := filepath.Join(dir, "wrapper.c"), filepath.Join(dir, "llama-server")
	if err := os.WriteFile(src, []byte(wrapperSource), 0o644); err != nil {
		t.Fatal(err)
	}
	res, err := execx.Exec{}.Run(context.Background(), execx.Cmd{
		Path: cc, Args: []string{"-O1", "-o", out, src}, Timeout: 2 * time.Minute, MaxOut: 1 << 20, Env: toolEnv(),
	})
	if err != nil || res.ExitCode != 0 {
		t.Fatalf("compiling the wrapper: %v (exit status %d)\n%s%s", err, res.ExitCode, res.Stdout, res.Stderr)
	}
	return readBytes(t, out)
}

// injectFailingServer writes a copy of the exported build src to dst in which bin/llama-server is the
// wrapper (and the real program is bin/llama-server.real), with BUILD.json recording the wrapper's
// sha256 so the archive is still a consistent prebuilt. It returns the sha256 of dst.
func injectFailingServer(t *testing.T, src, dst string, wrapper []byte) string {
	t.Helper()
	in, err := os.Open(src)
	if err != nil {
		t.Fatal(err)
	}
	defer in.Close()
	gz, err := gzip.NewReader(in)
	if err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	zw := gzip.NewWriter(&out)
	zw.Header = gzip.Header{}
	tw := tar.NewWriter(zw)
	put := func(h *tar.Header, b []byte) {
		h.Size = int64(len(b))
		if err := tw.WriteHeader(h); err != nil {
			t.Fatal(err)
		}
		if _, err := tw.Write(b); err != nil {
			t.Fatal(err)
		}
	}
	tr := tar.NewReader(gz)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			t.Fatal(err)
		}
		if h.Typeflag != tar.TypeReg {
			if err := tw.WriteHeader(h); err != nil {
				t.Fatal(err)
			}
			continue
		}
		b, err := io.ReadAll(tr)
		if err != nil {
			t.Fatal(err)
		}
		switch h.Name {
		case "bin/llama-server":
			real := *h
			real.Name = "bin/llama-server.real"
			put(&real, b)
			put(h, wrapper)
		case "BUILD.json":
			var doc map[string]any
			if err := json.Unmarshal(b, &doc); err != nil {
				t.Fatal(err)
			}
			sha, _ := doc["sha256"].(map[string]any)
			w := sha256.Sum256(wrapper)
			sha["llama-server"] = hex.EncodeToString(w[:])
			nb, err := json.Marshal(doc)
			if err != nil {
				t.Fatal(err)
			}
			put(h, nb)
		default:
			put(h, b)
		}
	}
	if err := tw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(dst, out.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	s := sha256.Sum256(out.Bytes())
	return hex.EncodeToString(s[:])
}

func failReal(t *testing.T, what string, err error) {
	t.Helper()
	var e *Error
	if errors.As(err, &e) {
		t.Fatalf("%s: %s: %s\n%v\n%v", what, e.Code, e.Message, e.Details["log_path"], e.Details["log_tail"])
	}
	t.Fatalf("%s: %v", what, err)
}

// resolveLink returns the directory current of root points at.
func resolveLink(t *testing.T, root string) string {
	t.Helper()
	p, err := filepath.EvalSymlinks(filepath.Join(root, currentLink))
	if err != nil {
		t.Fatal(err)
	}
	// Both sides are compared as real paths (a temp directory may itself sit behind a link).
	return p
}

func readBytes(t *testing.T, p string) []byte {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func fileSHA(t *testing.T, p string) string {
	t.Helper()
	s := sha256.Sum256(readBytes(t, p))
	return hex.EncodeToString(s[:])
}
