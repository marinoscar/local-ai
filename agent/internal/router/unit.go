// The two modes of node.yaml llama.mode (llama-router.md section 4.8).
const (
	LlamaModeRouter = "router"
	LlamaModeSingle = "single"
)

// Fixed names of the llama unit (llama-router.md sections 3.1 and 3.2, overview.md section 3.2). They
// are the canonical paths of the lab: the generated text never varies with the host.
const (
	// DefaultLlamaBinary is the binary the unit always runs: the build manager moves the "current"
	// symlink, the unit never changes (section 3.1).
	DefaultLlamaBinary = "/opt/localai/llama.cpp/current/bin/llama-server"
	// UnitWorkDir is the unit's WorkingDirectory and its only writable path.
	UnitWorkDir = "/var/lib/localai"
	// LlamaCacheDir is LLAMA_CACHE: kept empty so the router lists no stray cache models.
	LlamaCacheDir = "/var/lib/localai/llama-cache"
	// UnitCredentialFile is the key file systemd loads with LoadCredential.
	UnitCredentialFile = "/etc/localai/api-key"
	// UnitPresetFile is the preset file of router mode (written by Generator).
	UnitPresetFile = "/etc/localai/models.ini"
	// DefaultLlamaPort is node.yaml ports.llama.
	DefaultLlamaPort = 8080
)

// UnitHeader is the first two lines of the generated unit. Unlike models.ini the unit carries no
// time or version, so two renderings of the same inputs are byte-identical.
const UnitHeader = "# GENERATED by aiagent — do not edit. Regenerated from node.yaml + catalog profile.\n" +
	"# Spec: docs/specs/llama-router.md §3.2\n"

// unitHeaderPrefix is what marks a unit file as ours when no hash is recorded.
const unitHeaderPrefix = "# GENERATED by aiagent "

