package acestep

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"strings"

	"github.com/marinoscar/local-ai/agent/internal/config"
)

// envFileMode is the mode of music.env: root:localai 0640, like whisper.env.
const envFileMode os.FileMode = 0o640

// Defaults of music.env (E11 contract section 1).
const (
	DefaultPort     = config.DefaultMusicPort
	DefaultDevice   = "cuda"
	DefaultDType    = "auto"
	DefaultMaxQueue = 4
)

// Env is the content of /etc/localai/music.env.
type Env struct {
	Port     int
	ModelID  string
	ModelDir string
	WorkDir  string
	// Device is cuda or cpu; DType auto, fp16, bf16 or fp32.
	Device   string
	DType    string
	MaxQueue int
}

var (
	devices = []string{"cuda", "cpu"}
	dtypes  = []string{"auto", "fp16", "bf16", "fp32"}
)

// withDefaults fills the zero fields.
func (e Env) withDefaults() Env {
	if e.Port == 0 {
		e.Port = DefaultPort
	}
	if e.WorkDir == "" {
		e.WorkDir = WorkDir
	}
	if e.Device == "" {
		e.Device = DefaultDevice
	}
	if e.DType == "" {
		e.DType = DefaultDType
	}
	if e.MaxQueue == 0 {
		e.MaxQueue = DefaultMaxQueue
	}
	return e
}

// Validate refuses a value that would make a broken or unsafe file: every value is one line, the
// paths are absolute, the enums are known.
func (e Env) Validate() error {
	e = e.withDefaults()
	for k, v := range map[string]string{"MUSIC_MODEL_ID": e.ModelID, "MUSIC_MODEL_DIR": e.ModelDir, "MUSIC_WORK_DIR": e.WorkDir} {
		if v == "" || strings.ContainsAny(v, "\n\r\x00\"'$`\\") {
			return fmt.Errorf("acestep: %s %q is empty or not a plain value", k, v)
		}
	}
	if !strings.HasPrefix(e.ModelDir, "/") || !strings.HasPrefix(e.WorkDir, "/") {
		return errors.New("acestep: the model and work directories must be absolute paths")
	}
	if e.Port < 1024 || e.Port > 65535 {
		return fmt.Errorf("acestep: port %d is out of range", e.Port)
	}
	if !contains(devices, e.Device) || !contains(dtypes, e.DType) {
		return fmt.Errorf("acestep: device %q or dtype %q is not known", e.Device, e.DType)
	}
	if e.MaxQueue < 1 || e.MaxQueue > 64 {
		return fmt.Errorf("acestep: max queue %d is out of range", e.MaxQueue)
	}
	return nil
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}

// RenderEnv returns the text of music.env. It is deterministic; call Validate first.
func RenderEnv(e Env) []byte {
	e = e.withDefaults()
	var b bytes.Buffer
	b.WriteString("# Generated by aiagent. Do not edit. Rewritten before every start of localai-music.\n")
	fmt.Fprintf(&b, "MUSIC_PORT=%d\n", e.Port)
	fmt.Fprintf(&b, "MUSIC_MODEL_ID=%s\n", e.ModelID)
	fmt.Fprintf(&b, "MUSIC_MODEL_DIR=%s\n", e.ModelDir)
	fmt.Fprintf(&b, "MUSIC_WORK_DIR=%s\n", e.WorkDir)
	fmt.Fprintf(&b, "MUSIC_DEVICE=%s\n", e.Device)
	fmt.Fprintf(&b, "MUSIC_DTYPE=%s\n", e.DType)
	fmt.Fprintf(&b, "MUSIC_MAX_QUEUE=%d\n", e.MaxQueue)
	return b.Bytes()
}

// EnvFile writes music.env.
type EnvFile struct {
	// Path is the file; default EnvPath.
	Path string
	// FS is the disk; default config.OSFS.
	FS config.FS
	// UID and GID own the file (root:localai); -1 leaves an id alone.
	UID, GID int
}

// Write validates e and replaces the file atomically when its bytes differ.
func (f EnvFile) Write(e Env) error {
	if err := e.Validate(); err != nil {
		return err
	}
	path := f.Path
	if path == "" {
		path = EnvPath
	}
	fsys := f.FS
	if fsys == nil {
		fsys = config.OSFS{}
	}
	data := RenderEnv(e)
	if cur, err := fsys.ReadFile(path); err == nil && bytes.Equal(cur, data) {
		return nil
	}
	if err := config.WriteFileAtomicFS(fsys, path, data, envFileMode, f.UID, f.GID); err != nil && !errors.Is(err, config.ErrNotDurable) {
		return fmt.Errorf("acestep: write %s: %w", path, err)
	}
	return nil
}
