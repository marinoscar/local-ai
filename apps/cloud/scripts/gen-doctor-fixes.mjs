#!/usr/bin/env node
// Generates apps/web/src/localai/doctorFixes.generated.ts from the registry docs/specs/doctor-codes.md (section 2): the
// plain-language meaning and fix of the codes a node's page can show (a failed command's error code, the last ark sync's
// error code). The page may not read the docs at run time, so the rows are copied here; the web test
// `doctorFixes.test.ts` fails when this file differs from what this script would write, so the copy cannot drift.
//
// Usage: node apps/cloud/scripts/gen-doctor-fixes.mjs [--check]     (from the repository root or apps/cloud)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The areas whose codes can reach the node page: cloud, sync, ark, llama router and catalog. */
export const AREAS = ['CLD', 'SYN', 'ARK', 'LLM', 'CAT'];

const here = dirname(fileURLToPath(import.meta.url));
const REGISTRY = join(here, '..', '..', '..', 'docs', 'specs', 'doctor-codes.md');
const OUT = join(here, '..', 'apps', 'web', 'src', 'localai', 'doctorFixes.generated.ts');

const clean = (cell) => cell.replace(/\*\*/g, '').replace(/\s+/g, ' ').trim();

/** Rows `| LAI-AAA-NNN | severity | meaning | fix |` of the registry, as { code, severity, meaning, fix }. */
export function parseRegistry(markdown) {
  const rows = [];
  for (const line of markdown.split('\n')) {
    const match = /^\|\s*(LAI-([A-Z]{2,3})-\d{3})\s*\|/.exec(line);
    if (!match || !AREAS.includes(match[2])) continue;
    const cells = line.split('|').map((cell) => cell.trim());
    // cells: ['', code, severity, meaning, fix, ...]
    if (cells.length < 5) continue;
    rows.push({ code: match[1], severity: clean(cells[2]), meaning: clean(cells[3]), fix: clean(cells[4]) });
  }
  return rows.sort((a, b) => a.code.localeCompare(b.code));
}

export function render(rows) {
  const body = rows.map((row) => `  '${row.code}': { severity: ${JSON.stringify(row.severity)}, meaning: ${JSON.stringify(row.meaning)}, fix: ${JSON.stringify(row.fix)} },`).join('\n');
  return `// GENERATED by apps/cloud/scripts/gen-doctor-fixes.mjs from docs/specs/doctor-codes.md. Do not edit by hand:
// edit the registry, then run \`node apps/cloud/scripts/gen-doctor-fixes.mjs\`. \`doctorFixes.test.ts\` fails on drift.
export interface DoctorFixRow {
  severity: string;
  meaning: string;
  fix: string;
}

export const DOCTOR_FIXES: Readonly<Record<string, DoctorFixRow>> = {
${body}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(parseRegistry(readFileSync(REGISTRY, 'utf8')));
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== text) {
      console.error('doctorFixes.generated.ts is out of date: run node apps/cloud/scripts/gen-doctor-fixes.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
